<?php
$x = 10;
$y = 3;
// penjumlahan
$penjumlahan = $x + $y;
echo $penjumlahan . "<br>";

// pengurangan
$pengurangan = $x - $y;
echo $pengurangan . "<br>";

// perkalian
$perkalian = $x * $y;
echo $perkalian . "<br>";

// pembagian
$pembagian = $x / $y;
printf("%.2f", $pembagian);

// modulus
$modulus = $x % $y;
echo "<br>" . $modulus . "<br>";

// pangkat
$pangkat = $x ** $y;
echo $pangkat . "<br>";
?>