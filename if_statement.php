<?php
$nilai = 80;

// if = akan menjalankan suatu code jika kondisinya benar
if ($nilai >= 75) {
    echo "Selamat, kamu lulus! <br>";
}

// jika nilai >= 90 menampilkan nilai sangat baik
if ($nilai >= 90) {
    echo "Nilai sangat baik! <br>";
}

// jika nilai >= 80 dan nilai < 90 maka menampilkan Nilai baik
if ($nilai >= 80 && $nilai < 90) {
    echo "Nilai Baik <br>";
}
?>