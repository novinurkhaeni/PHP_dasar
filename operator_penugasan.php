<?php
// Operator penugasan adalah untuk mengisi nilai dalam variabel

// = memberikan nilai ke variabel
$x = 10;
echo "Nilai x = $x <br>"; //10

// += menggabungkan penjumlahan dan =
$x += 5; //x = x + 5 = 15
echo "Nilai x += 5 adalah $x <br>";

// -= menggabungkan pengurangan dan =
$x -= 3; //x = x -3 = 12
echo "Nilai x -= 3 adalah $x <br>";

// *= menggabungkan perkalian dan =
$x *= 2; //x = x * 2 = 24
echo "Nilai x *= 2 adalah $x <br>";

// /= menggabungkan pembagian dan =
$x /= 4; //x = x / 4 = 6
echo "Nilai x /= 4 adalah $x <br>";

// %= menggabungkan modulus dan =
$x %= 5; //x = x % 5 =1
echo "Nilai x %= 5 adalah $x <br>";
